#!/usr/bin/env python3
"""
Generate `build/strata_embedded_shaders.cpp` containing all Metal 4 kernels and
shared GPU/host ABI headers so `strata-apex` runs as a self-contained single binary.
"""
import os
import sys

ASSETS = [
    ("strata_kernels.metal",                 "src/gpu/strata_kernels.metal"),
    ("strata_abi.h",                         "include/strata_abi.h"),
    ("strata_qwen38_kernels.metal",          "src/gpu/strata_qwen38_kernels.metal"),
    ("strata_qwen38.h",                      "include/strata_qwen38.h"),
    ("strata_qwen_flash_kernels.metal",      "src/gpu/strata_qwen_flash_kernels.metal"),
    ("strata_qwen_flash.h",                  "include/strata_qwen_flash.h"),
    ("strata_glm53_kernels.metal",           "src/gpu/strata_glm53_kernels.metal"),
    ("strata_glm53.h",                       "include/strata_glm53.h"),
    ("strata_inkling2_kernels.metal",        "src/gpu/strata_inkling2_kernels.metal"),
    ("strata_inkling2.h",                    "include/strata_inkling2.h"),
    ("strata_inkling2_vision_kernels.metal", "src/gpu/strata_inkling2_vision_kernels.metal"),
    ("strata_inkling2_vision.h",             "include/strata_inkling2_vision.h"),
]

def main() -> int:
    if len(sys.argv) != 2:
        sys.stderr.write("Usage: embed_shaders.py <out_cpp_path>\n")
        return 1
    out_path = sys.argv[1]
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)

    lines = [
        "/* Auto-generated by scripts/embed_shaders.py — DO NOT EDIT */",
        '#include "strata_embedded_shaders.h"',
        "#include <cstring>",
        "",
        "namespace {",
        "",
    ]

    entries = []
    for idx, (key, rel_path) in enumerate(ASSETS):
        with open(rel_path, "rb") as f:
            raw = f.read()
        sym = f"kAsset_{idx}"
        lines.append(f"static const unsigned char {sym}[] = {{")
        # Emit compact hex rows (24 bytes/line) so clang++ compiles in <0.25s
        for off in range(0, len(raw), 24):
            chunk = raw[off : off + 24]
            lines.append("  " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
        lines.append("  0x00")
        lines.append("};")
        lines.append("")
        entries.append((key, sym, len(raw)))

    lines.append("} // namespace")
    lines.append("")
    lines.append('extern "C" const char* strata_embedded_asset_lookup(const char* key, size_t* len_out) {')
    lines.append("    if (!key) return nullptr;")
    for key, sym, sz in entries:
        lines.append(f'    if (std::strcmp(key, "{key}") == 0) {{')
        lines.append(f"        if (len_out) *len_out = {sz}U;")
        lines.append(f"        return reinterpret_cast<const char*>({sym});")
        lines.append("    }")
    lines.append("    return nullptr;")
    lines.append("}")
    lines.append("")

    content = "\n".join(lines)
    # Only rewrite if changed so incremental `make` stays instant
    if os.path.exists(out_path):
        with open(out_path, "r", encoding="utf-8") as f:
            if f.read() == content:
                return 0
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
